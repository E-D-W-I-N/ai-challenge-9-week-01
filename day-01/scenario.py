"""День 01 — одна сессия: промпт → ответ.

Самый простой сценарий челленджа: одна колонка, один вызов, никаких сравнений.
Задача дня — показать зрителю панель метрик стенда: TTFT, живой счётчик ток/с,
рост счётчика токенов, prompt/completion/total, стоимость, finish_reason,
фактический провайдер, заполнение контекста.

Отсюда и требования к промпту: ответ должен стримиться несколько секунд
(ориентир 200-400 токенов), читаться на видео и завершиться сам —
max_tokens не задаём, чтобы finish_reason был stop, а не length.
"""

from app.schema import Scenario, Session

SYSTEM_PROMPT = (
    "Ты объясняешь технические вещи коротко, конкретно и живым языком. "
    "Без вступлений вроде «отличный вопрос», без маркированных списков "
    "и без финального резюме. Отвечай по-русски."
)

USER_PROMPT = (
    "Объясни, почему первый токен от языковой модели приходит заметно позже, "
    "чем все следующие. Разбери задержку по этапам: дорога запроса до провайдера, "
    "ожидание в очереди на GPU, префилл промпта, собственно генерация. "
    "На каждый этап — один абзац: что там происходит, растёт ли этот этап "
    "с длиной промпта и что с ним можно сделать на практике. "
    "Без вступления и без итогового абзаца."
)

SCENARIO = Scenario(
    id="day-01",
    title="День 01 — промпт → ответ",
    description=(
        "Один промпт, одна модель, один стриминговый ответ — и вся панель метрик "
        "стенда на нём. Модель объясняет, из чего складывается задержка до первого "
        "токена, пока стенд рядом измеряет ровно эту задержку на живом запросе."
    ),
    watch_for=(
        "TTFT — сколько прошло до первой буквы. Счётчик ток/с: он оживает на первом "
        "чанке и держится примерно ровно всю генерацию. Счётчик сгенерированных "
        "токенов растёт непрерывно. В конце приходит usage: prompt / completion / "
        "total, стоимость в долларах, finish_reason = stop (ответ закончился сам, "
        "а не был обрезан), фактический провайдер и заполнение контекста в процентах."
    ),
    layout="single",
    # Сравнивать в этом дне нечего — колонка одна, поэтому судью спрашиваем
    # не про разницу между колонками, а про сам результат: по существу ли
    # ответ, выдержана ли форма, нет ли вранья. Требования промпта повторены
    # внутри вопросов: самого промпта судья не видит, ему уходят только
    # description, note, параметры, метрики и текст ответа (watch_for стенд
    # судье не отправляет).
    judge_questions=[
        "Промпт требовал разобрать задержку до первого токена по четырём этапам — "
        "дорога запроса до провайдера, ожидание в очереди на GPU, префилл промпта, "
        "генерация — и на каждом сказать, растёт ли он с длиной промпта и что с ним "
        "делать на практике. Что из этого в ответе разобрано, а что пропущено "
        "или сказано вскользь?",
        "Форма была задана жёстко: один абзац на этап, без вступления, без "
        "маркированных списков и без итогового резюме, по-русски. Где ответ "
        "от неё отходит?",
        "Есть ли в ответе фактические ошибки или спорные утверждения о том, "
        "из чего складывается задержка до первого токена? Укажи конкретные места.",
    ],
    sessions=[
        Session(
            label="Ответ",
            model="mistralai/mistral-small-3.2-24b-instruct",
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": USER_PROMPT},
            ],
            # temperature не задаём: провайдер применит свой дефолт.
            # День 01 не про параметры сэмплинга — чем меньше лишних полей
            # в запросе, тем честнее читается базовая статистика.
            note=(
                "Модель без reasoning, ответ идёт сразу — TTFT остаётся в районе "
                "десятых долей секунды. max_tokens не задан: ответ должен "
                "закончиться сам и показать finish_reason = stop."
            ),
        ),
    ],
)
