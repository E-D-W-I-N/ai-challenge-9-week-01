"""День 03 — split ×4: прямо / пошагово / модель пишет промпт себе / панель экспертов.

Четыре техники разложены на три сценария: «прямо» отдельным сценарием быть не
может — сравнивать не с чем, поэтому она живёт колонкой-базой внутри первых двух.

    1. day-03-direct-vs-steps — прямо vs пошагово          (2 колонки)
    2. day-03-self-prompt     — прямо / промпт / ответ     (3 колонки, depends_on)
    3. day-03-panel           — аналитик / инженер / критик (3 колонки, параллельно)

Задача одна на все три сценария (TASK, про курьера): день сравнивает четыре
способа решить одну задачу, поэтому у всех колонок общий эталон — 20 км/ч и
48 минут — и общая ось точности.

Панель экспертов — это три независимых вызова API с разными системными ролями,
а не три агента: никакой оркестрации внутри сценария нет. `depends_on` в панели
не нужен и не используется — все три колонки стартуют одновременно.
"""

from __future__ import annotations

from app.schema import Scenario, Session

# Модель намеренно НЕ reasoning: reasoning-модель сама делает то, что показывает
# колонка «пошагово», и разница между колонками схлопнулась бы.
MODEL = "openai/gpt-4o-mini"

# Одинаковые во всех колонках всех сценариев, чтобы единственной переменной
# осталась техника промпта.
TEMPERATURE = 0.2
MAX_TOKENS = 1000

# ---------------------------------------------------------------------------
# Задача дня — одна на все три сценария
# ---------------------------------------------------------------------------

# Ловушка двухслойная:
#   слой 1 — среднее арифметическое (15+30)/2 = 22.5 ≈ 22 км/ч выглядит верным
#            и уже подсказано в условии; верно 24 км / 1.2 ч = 20 км/ч;
#   слой 2 — клиент ждёт только гружёное плечо: 12 / 15 = 48 минут, а по любой
#            круговой средней получится 33–36 минут, то есть метрика не та.
TASK = """Курьерский сервис возит заказ по маршруту «склад → клиент → склад».
Плечо в одну сторону — 12 км.
Гружёный курьер едет со средней скоростью 15 км/ч, порожняком назад — 30 км/ч.
В презентации для клиентов сервис пишет: «средняя скорость курьера на маршруте — 22 км/ч» — и по этой цифре считает обещанное клиенту время доставки.
Вопрос: какая у курьера средняя скорость на полном круге и корректно ли считать по ней время доставки клиенту?"""

# ---------------------------------------------------------------------------
# Сценарий 3: та же задача про курьера, но глазами трёх ролей
# ---------------------------------------------------------------------------

# Панель работает над ТОЙ ЖЕ TASK, что и остальные два сценария: день сравнивает
# четыре способа решить одну задачу, поэтому у панели должен быть тот же эталон
# (20 км/ч, 48 минут) и та же ось точности. Сойдутся три роли на одном ответе
# или разойдутся — это и есть результат сравнения, ради которого день снимается.

# Формат и запрет — общий хвост системного сообщения всех трёх ролей. Итоговая
# строка одинаковая у всех: она кладёт три мнения на ту же ось точности, что и
# ответы остальных трёх способов, и её видно, не читая колонку целиком.
PANEL_FORMAT = """Закончи строкой ровно такого вида, одной строкой и без пояснений после неё:
`ВЕРДИКТ: средняя на круге <число> км/ч; считать по ней время доставки клиенту — можно / нельзя`
До неё — не больше пяти пунктов, каждый со своей позиции. Не рассуждай о том, что вне твоей зоны ответственности."""


def _p(template: str) -> str:
    """Подставляет условие про курьера вместо <<ЗАДАЧА>>.

    Именно .replace, а не f-string: в f-string литерал {{depends_on}} схлопнулся бы
    в {depends_on}, и подстановка стенда перестала бы срабатывать.
    """
    return template.replace("<<ЗАДАЧА>>", TASK)


def _session(label: str, content: str, note: str, **kwargs) -> Session:
    """Колонка с одним user-сообщением и общими для дня параметрами."""
    return Session(
        label=label,
        model=MODEL,
        messages=[{"role": "user", "content": content}],
        temperature=TEMPERATURE,
        max_tokens=kwargs.pop("max_tokens", MAX_TOKENS),
        note=note,
        **kwargs,
    )


def _panel_session(label: str, role: str, note: str) -> Session:
    """Колонка панели: роль жёстко в системном сообщении, общая задача — в user."""
    return Session(
        label=label,
        model=MODEL,
        messages=[
            {"role": "system", "content": f"{role}\n\n{PANEL_FORMAT}"},
            {"role": "user", "content": TASK},
        ],
        temperature=TEMPERATURE,
        max_tokens=MAX_TOKENS,
        note=note,
    )


