"""День 03 — split ×4: прямо / пошагово / модель пишет промпт себе / панель экспертов.

Четыре техники разложены на три сценария: «прямо» отдельным сценарием быть не
может — сравнивать не с чем, поэтому она живёт колонкой-базой внутри первых двух.

    1. day-03-direct-vs-steps — прямо vs пошагово          (2 колонки)
    2. day-03-self-prompt     — прямо / промпт / ответ     (3 колонки, depends_on)
    3. day-03-panel           — аналитик / инженер / критик (3 колонки, параллельно)

Панель экспертов — это три независимых вызова API с разными системными ролями,
а не три агента: никакой оркестрации внутри сценария нет. `depends_on` в панели
не нужен и не используется — все три колонки стартуют одновременно.
"""

from __future__ import annotations

from app.schema import Scenario, Session

# Модель намеренно НЕ reasoning: reasoning-модель сама делает то, что показывает
# колонка «пошагово», и разница между колонками схлопнулась бы.
MODEL = "openai/gpt-4o-mini"

# Одинаковые во всех колонках всех сценариев, чтобы единственной переменной
# осталась техника промпта.
TEMPERATURE = 0.2
MAX_TOKENS = 1000

# ---------------------------------------------------------------------------
# Сценарии 1 и 2: задача про курьера
# ---------------------------------------------------------------------------

# Ловушка двухслойная:
#   слой 1 — среднее арифметическое (15+30)/2 = 22.5 ≈ 22 км/ч выглядит верным
#            и уже подсказано в условии; верно 24 км / 1.2 ч = 20 км/ч;
#   слой 2 — клиент ждёт только гружёное плечо: 12 / 15 = 48 минут, а по любой
#            круговой средней получится 33–36 минут, то есть метрика не та.
TASK = """Курьерский сервис возит заказ по маршруту «склад → клиент → склад».
Плечо в одну сторону — 12 км.
Гружёный курьер едет со средней скоростью 15 км/ч, порожняком назад — 30 км/ч.
В презентации для клиентов сервис пишет: «средняя скорость курьера на маршруте — 22 км/ч» — и по этой цифре считает обещанное клиенту время доставки.
Вопрос: какая у курьера средняя скорость на полном круге и корректно ли считать по ней время доставки клиенту?"""

# ---------------------------------------------------------------------------
# Сценарий 3: кейс для панели экспертов
# ---------------------------------------------------------------------------

# Задача про курьера для панели не годится: там один верный ответ, и три роли
# на нём сойдутся. Здесь — выбор с компромиссом, где каждая роль оптимизирует
# своё, а числа даны, чтобы аналитику было что считать.
CASE = """Интернет-магазин: 200 000 визитов в месяц, 4% доходят до оформления, из них 30% бросают заказ на форме доставки. Средний чек 3 500 ₽, маржа 20%. Продакт предлагает убрать обязательную регистрацию и оформлять заказ по номеру телефона с кодом из SMS. Оценка команды — 6 недель работы двух разработчиков, SMS стоит 3 ₽. Оцени предложение со своей позиции и дай вердикт."""

# Формат и запрет — общий хвост системного сообщения всех трёх ролей. Без него
# колонки сползают в одинаковый «взвешенный обзор» и панель теряет смысл.
PANEL_FORMAT = """Закончи строкой `ВЕРДИКТ: делать / не делать / сначала измерить`. До неё — не больше пяти пунктов, каждый со своей позиции. Не рассуждай о том, что вне твоей зоны ответственности."""


def _p(template: str) -> str:
    """Подставляет условие про курьера вместо <<ЗАДАЧА>>.

    Именно .replace, а не f-string: в f-string литерал {{depends_on}} схлопнулся бы
    в {depends_on}, и подстановка стенда перестала бы срабатывать.
    """
    return template.replace("<<ЗАДАЧА>>", TASK)


def _session(label: str, content: str, note: str, **kwargs) -> Session:
    """Колонка с одним user-сообщением и общими для дня параметрами."""
    return Session(
        label=label,
        model=MODEL,
        messages=[{"role": "user", "content": content}],
        temperature=TEMPERATURE,
        max_tokens=kwargs.pop("max_tokens", MAX_TOKENS),
        note=note,
        **kwargs,
    )


def _panel_session(label: str, role: str, note: str) -> Session:
    """Колонка панели: роль задана жёстко в системном сообщении, кейс — в user."""
    return Session(
        label=label,
        model=MODEL,
        messages=[
            {"role": "system", "content": f"{role}\n\n{PANEL_FORMAT}"},
            {"role": "user", "content": CASE},
        ],
        temperature=TEMPERATURE,
        max_tokens=MAX_TOKENS,
        note=note,
    )


# ---------------------------------------------------------------------------
# 1 · Прямо vs пошагово
# ---------------------------------------------------------------------------

DIRECT_VS_STEPS = Scenario(
    id="day-03-direct-vs-steps",
    title="Прямо vs пошагово",
    description=(
        "Одна модель, одна задача, две колонки: слева условие как есть, справа "
        "то же условие плюс требование рассуждать по шагам и проверять каждый шаг "
        "на противоречие с условием. Задача с ловушкой: курьер едет «склад → клиент "
        "→ склад», плечо 12 км, гружёным 15 км/ч, порожняком 30 км/ч, а в презентации "
        "написано «средняя 22 км/ч». 22.5 — это среднее арифметическое скоростей, и оно "
        "здесь не работает: верный ответ 24 км / 1.2 ч = 20 км/ч. Второй слой ловушки — "
        "по круговой средней вообще нельзя считать время доставки, клиент ждёт только "
        "гружёное плечо, 12 / 15 = 48 минут."
    ),
    watch_for=(
        "1) Левая колонка обычно садится в подсказанную условием ловушку и "
        "подтверждает 22–22.5 км/ч; правая пересчитывает через время и выходит "
        "на 20 км/ч, а нередко ловит и второй слой — про 48 минут. "
        "2) Смотрите на статистику колонок рядом: у правой заметно больше "
        "completion-токенов и выше стоимость. Пошаговое рассуждение — это не "
        "бесплатная приправа к промпту, на панели видно, во сколько именно "
        "обошлась правота. 3) TTFT у колонок примерно одинаковый, а вот время "
        "до конца ответа у правой ощутимо больше — она дольше печатает."
    ),
    layout="split",
    sessions=[
        _session(
            "Прямо",
            _p("<<ЗАДАЧА>>"),
            "База: задача как есть, ноль указаний. Во что модель падает по "
            "умолчанию, когда неверный ответ уже подсказан в условии.",
        ),
        _session(
            "Пошагово",
            _p(
                """<<ЗАДАЧА>>

Прежде чем дать ответ, рассуждай по шагам: выпиши, что дано, посчитай промежуточные величины, проверь каждый шаг на противоречие с условием. Только после этого сформулируй вывод."""
            ),
            "Та же задача плюс требование рассуждать по шагам. Указание намеренно "
            "общее: продиктуй структуру решения — и колонка померит подсказку, "
            "а не технику.",
        ),
    ],
)

# ---------------------------------------------------------------------------
# 2 · Модель пишет промпт себе
# ---------------------------------------------------------------------------

# depends_on ссылается на label другой колонки этого же сценария, и опечатка в
# строке молча вешает колонку с ошибкой — поэтому метка вынесена в константу.
L_WRITES_PROMPT = "Модель пишет промпт"

SELF_PROMPT = Scenario(
    id="day-03-self-prompt",
    title="Модель пишет промпт себе",
    description=(
        "Три колонки на одной задаче про курьера (плечо 12 км, гружёным 15 км/ч, "
        "порожняком 30 км/ч, в презентации «средняя 22 км/ч»; верно 20 км/ч, "
        "а время доставки по круговой средней считать вообще нельзя). Слева — "
        "«Прямо», точка отсчёта. В середине модель не решает задачу, а сочиняет "
        "промпт, который заставит решить её правильно. Справа — та же модель "
        "отвечает уже по этому самопальному промпту: её сообщение собирается "
        "стендом из вывода средней колонки через depends_on. Это единственный "
        "сценарий дня, где используется depends_on."
    ),
    watch_for=(
        "1) Средняя колонка выдаёт не ответ, а текст промпта — там нет ни 20, ни "
        "22 км/ч, там инструкции. 2) Правая колонка всё это время висит со статусом "
        "«ждёт вывод колонки», стартует только после средней и печатает уже ответ. "
        "3) Откройте у правой колонки «показать промпт»: там лежит не то, что "
        "написано в scenario.py, а текст, сочинённый моделью в средней колонке. "
        "4) Сравнивайте крайние колонки — левую и правую: разница между ними и есть "
        "то, что дал самосоставленный промпт. Исход честный в обе стороны: если "
        "модель не предупредила себя про ловушку, правая колонка ошибётся так же, "
        "как левая."
    ),
    layout="split",
    sessions=[
        _session(
            "Прямо",
            _p("<<ЗАДАЧА>>"),
            "Точка отсчёта: та же задача без единого указания. С этой колонкой "
            "сравниваем правую.",
        ),
        _session(
            L_WRITES_PROMPT,
            _p(
                """Ты составляешь промпт для языковой модели. Вот задача, которую ей предстоит решить:

<задача>
<<ЗАДАЧА>>
</задача>

Напиши наилучший промпт, который заставит модель решить эту задачу правильно и не попасться в ловушку, если ловушка здесь есть. Промпт должен быть самодостаточным: он целиком содержит условие задачи и все нужные требования к ответу.

Выведи только текст промпта — без вступления, без пояснений, без заголовков и без кавычек вокруг."""
            ),
            "Модель не решает задачу, а пишет промпт для себя. Её вывод целиком "
            "уходит в правую колонку.",
            max_tokens=450,
        ),
        _session(
            "Ответ по своему промпту",
            """{{depends_on}}

(Выполни инструкцию выше и дай ответ.)""",
            "depends_on = «Модель пишет промпт». Стенд подставляет сюда вывод "
            "соседней колонки вместо {{depends_on}} и стартует эту колонку "
            "только после неё.",
            depends_on=L_WRITES_PROMPT,
        ),
    ],
)

