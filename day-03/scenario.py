# Задание Дня 3 спрашивает две вещи: «отличаются ли ответы» и «какой способ дал
# наиболее точный результат». До сих пор на второй вопрос отвечал зритель — теперь
# отвечает судья, и он же единственный, кто может: ответ «какой точнее» требует
# решить задачу, а колонки её решают каждая по-своему.
#
# Эталон (20 км/ч и «нельзя») судье не сообщается ни одним вопросом: он должен
# получить его сам, иначе вердикт превратится в сверку с подсказкой, а «самый
# точный способ» определит промпт судьи, а не техника колонки. По той же причине
# ни один вопрос не намекает, что в задаче есть ловушка и что какая-то колонка
# в неё попалась.
#
# Отсюда общая формулировка вопроса о точности: она велит судье решить задачу
# самому и не верить колонке на слово — та бывает уверена и неправа.
JUDGE_ACCURACY = (
    "Какой способ дал более точный результат — назови колонку. Посчитай задачу "
    "сам и сверь с числами и выводами колонок; уверенность в тоне ответа за "
    "точность не считай."
)

