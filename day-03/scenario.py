# 2 · Модель пишет промпт себе
# ---------------------------------------------------------------------------

# depends_on ссылается на label другой колонки этого же сценария, и опечатка в
# строке молча вешает колонку с ошибкой — поэтому метка вынесена в константу.
L_WRITES_PROMPT = "Модель пишет промпт"

SELF_PROMPT = Scenario(
    id="day-03-self-prompt",
    title="Модель пишет промпт себе",
    description=(
        "Три колонки на одной задаче про курьера (плечо 12 км, гружёным 15 км/ч, "
        "порожняком 30 км/ч, в презентации «средняя 22 км/ч»; верно 20 км/ч, "
        "а время доставки по круговой средней считать вообще нельзя). Слева — "
        "«Прямо», точка отсчёта. В середине модель не решает задачу, а сочиняет "
        "промпт, который заставит решить её правильно. Справа — та же модель "
        "отвечает уже по этому самопальному промпту: её сообщение собирается "
        "стендом из вывода средней колонки через depends_on. Это единственный "
        "сценарий дня, где используется depends_on."
    ),
    watch_for=(
        "1) Средняя колонка выдаёт не ответ, а текст промпта — там нет ни 20, ни "
        "22 км/ч, там инструкции. 2) Правая колонка всё это время висит со статусом "
        "«ждёт вывод колонки», стартует только после средней и печатает уже ответ. "
        "3) Откройте у правой колонки «показать промпт»: там лежит не то, что "
        "написано в scenario.py, а текст, сочинённый моделью в средней колонке. "
        "4) Сравнивайте крайние колонки — левую и правую: разница между ними и есть "
        "то, что дал самосоставленный промпт. Исход честный в обе стороны: если "
        "модель не предупредила себя про ловушку, правая колонка ошибётся так же, "
        "как левая."
    ),
    layout="split",
    sessions=[
        _session(
            "Прямо",
            _p("<<ЗАДАЧА>>"),
            "Точка отсчёта: та же задача без единого указания. С этой колонкой "
            "сравниваем правую.",
        ),
        _session(
            L_WRITES_PROMPT,
            _p(
                """Ты составляешь промпт для языковой модели. Вот задача, которую ей предстоит решить:

<задача>
<<ЗАДАЧА>>
</задача>

Напиши наилучший промпт, который заставит модель решить эту задачу правильно и не попасться в ловушку, если ловушка здесь есть. Промпт должен быть самодостаточным: он целиком содержит условие задачи и все нужные требования к ответу.

Выведи только текст промпта — без вступления, без пояснений, без заголовков и без кавычек вокруг."""
            ),
            "Модель не решает задачу, а пишет промпт для себя. Её вывод целиком "
            "уходит в правую колонку.",
            max_tokens=450,
        ),
        _session(
            "Ответ по своему промпту",
            """{{depends_on}}

(Выполни инструкцию выше и дай ответ.)""",
            "depends_on = «Модель пишет промпт». Стенд подставляет сюда вывод "
            "соседней колонки вместо {{depends_on}} и стартует эту колонку "
            "только после неё.",
            depends_on=L_WRITES_PROMPT,
        ),
    ],
)

