# 1 · Прямо vs пошагово
# ---------------------------------------------------------------------------

DIRECT_VS_STEPS = Scenario(
    id="day-03-direct-vs-steps",
    title="Прямо vs пошагово",
    description=(
        "Одна модель, одна задача, две колонки: слева условие как есть, справа "
        "то же условие плюс требование рассуждать по шагам и проверять каждый шаг "
        "на противоречие с условием. Задача с ловушкой: курьер едет «склад → клиент "
        "→ склад», плечо 12 км, гружёным 15 км/ч, порожняком 30 км/ч, а в презентации "
        "написано «средняя 22 км/ч». 22.5 — это среднее арифметическое скоростей, и оно "
        "здесь не работает: верный ответ 24 км / 1.2 ч = 20 км/ч. Второй слой ловушки — "
        "по круговой средней вообще нельзя считать время доставки, клиент ждёт только "
        "гружёное плечо, 12 / 15 = 48 минут."
    ),
    watch_for=(
        "1) Левая колонка обычно садится в подсказанную условием ловушку и "
        "подтверждает 22–22.5 км/ч; правая пересчитывает через время и выходит "
        "на 20 км/ч, а нередко ловит и второй слой — про 48 минут. "
        "2) Смотрите на статистику колонок рядом: у правой заметно больше "
        "completion-токенов и выше стоимость. Пошаговое рассуждение — это не "
        "бесплатная приправа к промпту, на панели видно, во сколько именно "
        "обошлась правота. 3) TTFT у колонок примерно одинаковый, а вот время "
        "до конца ответа у правой ощутимо больше — она дольше печатает."
    ),
    layout="split",
    sessions=[
        _session(
            "Прямо",
            _p("<<ЗАДАЧА>>"),
            "База: задача как есть, ноль указаний. Во что модель падает по "
            "умолчанию, когда неверный ответ уже подсказан в условии.",
        ),
        _session(
            "Пошагово",
            _p(
                """<<ЗАДАЧА>>

Прежде чем дать ответ, рассуждай по шагам: выпиши, что дано, посчитай промежуточные величины, проверь каждый шаг на противоречие с условием. Только после этого сформулируй вывод."""
            ),
            "Та же задача плюс требование рассуждать по шагам. Указание намеренно "
            "общее: продиктуй структуру решения — и колонка померит подсказку, "
            "а не технику.",
        ),
    ],
)

