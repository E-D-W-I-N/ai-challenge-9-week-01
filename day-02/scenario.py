"""День 02 — split: свободный ответ против формата и ограничений.

Обе колонки — одна и та же модель и один и тот же вопрос. Отличаются только
параметры запроса, поэтому любую разницу в выводе можно честно списать на них.

Наблюдаемый эффект дня даёт max_tokens: у правой колонки finish_reason
станет length, а ответ оборвётся заметно раньше левой.

Про response_format: слово «JSON» обязано встречаться в тексте промпта, иначе
модели семейства OpenAI возвращают 400 на response_format={"type": "json_object"}.
Здесь оно есть естественным образом — вопрос как раз про форматы обмена данными,
и это не стилистика, а условие работоспособности колонки B.

Про stop: стоп-строка выбрана заведомо недостижимой. Если бы она сработала
раньше лимита, finish_reason стал бы stop — и единственный видимый сигнал дня
пропал бы. Подробности — в README.md.
"""

from __future__ import annotations

from app.schema import Scenario, Session

# Одна модель на обе колонки. openai/gpt-4o-mini поддерживает response_format,
# max_tokens и stop — стенд шлёт provider.require_parameters=true, поэтому запрос
# не уедет к провайдеру, который молча проигнорирует ограничения.
MODEL = "openai/gpt-4o-mini"

# Один и тот же вопрос в обеих колонках — иначе разницу нельзя приписать параметрам.
# Ответ на него «хочет» быть длинным (300+ токенов), что и нужно для обрыва.
QUESTION = (
    "Ты объясняешь junior-бэкендеру форматы обмена данными между сервисами. "
    "Разбери подробно, чем JSON отличается от JSON Lines и от MessagePack: "
    "как устроен каждый формат, в каких задачах выбирают именно его, "
    "и какие подводные камни ждут при сериализации больших чисел, дат и null. "
    "По каждому формату дай пример и отдельно назови типичную ошибку."
)

MESSAGES = [{"role": "user", "content": QUESTION}]

# Строка-сентинел: модель не просят её писать, и в JSON-ответе она появиться
# не может. Параметр stop уходит в запрос, провайдер его принимает — и ровно
# ничего не видно. Это и есть урок дня про stop.
STOP = ["<<<КОНЕЦ_ОТВЕТА>>>"]

# Свободный ответ на такой вопрос — сотни токенов. 80 гарантирует обрыв,
# а не «как повезёт».
LIMIT = 80

SCENARIO = Scenario(
    id="day-02",
    title="День 02 — свободный ответ против формата и ограничений",
    description=(
        "Слева и справа одна и та же модель и дословно один и тот же вопрос. "
        "Меняются только параметры запроса: левая колонка не задаёт ничего, "
        "правая получает response_format={'type': 'json_object'}, "
        f"max_tokens={LIMIT} и stop. "
        "Смысл дня: параметр может работать и не оставлять следа в выводе. "
        "stop здесь уходит в запрос и остаётся невидимым, а max_tokens виден сразу — "
        "по finish_reason и по длине ответа."
    ),
    watch_for=(
        f"finish_reason: слева stop, справа length — это и есть сигнал от max_tokens={LIMIT}. "
        "Длина: справа ответ обрывается на полуслове, слева идёт до конца, "
        "разница видна и по счётчику completion-токенов. "
        "Форма: слева свободный текст, справа JSON-объект — но оборванный, "
        "то есть невалидный: response_format гарантирует формат только тому ответу, "
        "которому хватило лимита. "
        "И то, чего НЕ видно: stop задан только справа, но в выводе он следа не оставил."
    ),
    layout="split",
    sessions=[
        Session(
            label="A. Свободный ответ",
            model=MODEL,
            messages=MESSAGES,
            note=(
                "Ни temperature, ни max_tokens, ни stop, ни response_format. "
                "Модель отвечает как хочет и заканчивает сама: finish_reason = stop."
            ),
        ),
        Session(
            label="B. Формат и ограничения",
            model=MODEL,
            messages=MESSAGES,
            response_format={"type": "json_object"},
            max_tokens=LIMIT,
            stop=STOP,
            note=(
                f"response_format=json_object, max_tokens={LIMIT}, stop={STOP[0]!r}. "
                "Лимит упирается первым: finish_reason = length, JSON обрывается "
                "недописанным. Стоп-строка недостижима и в выводе не видна."
            ),
        ),
    ],
)
