"""День 02 — split: свободный ответ vs. формат + max_tokens + stop.

Три сценария, по одному на параметр, в порядке пунктов задания:

    day-02-format  — response_format={"type": "json_object"}
    day-02-length  — max_tokens
    day-02-stop    — stop

База у всех трёх общая: одна модель и один и тот же вопрос про форматы обмена
данными — дословно один текст на все шесть колонок дня. Так требует задание:
«отправьте один и тот же запрос, но добавьте формат / ограничение длины / условие
завершения», то есть разницу обязаны давать только параметры. В каждом сценарии
левая колонка не задаёт ни одного параметра, правая меняет ровно один — поэтому
разницу в кадре можно честно приписать этому параметру, а не промпту, не модели
и не сумме эффектов.

Общий вопрос просит пронумерованный разбор — «1)», «2)», «3)». Это не украшение:
на маркере второго пункта стоит стоп-строка сценария day-02-stop, и без явно
заданной разметки она в ответе просто не встретится. Двум другим сценариям
нумерация не мешает: max_tokens режет текст по счётчику токенов независимо от
разметки, а response_format гарантирует валидный JSON-объект — и форму этого
объекта определяет параметр, а не разметка из промпта. Как именно модель уложит
в него пункты (полями, списком или строками с теми же маркерами), не гарантирует
никто, и это нормально: сравниваем текст против структуры, а не разметку.

Раньше все три параметра стояли в одной правой колонке, и по такому кадру нельзя
было сказать, чей эффект какой: лимит обрывал JSON, и урок про формат смазывался.
Теперь JSON приходит целым, обрыв показывается отдельно, а stop — отдельно.

Подводные камни, каждый ломает свой сценарий молча:

* response_format={"type": "json_object"} возвращает 400 на моделях семейства
  OpenAI, если в самом тексте промпта не встречается слово «JSON». Здесь оно есть
  естественным образом — вопрос как раз про JSON и его родственников. Это не
  стилистика, а условие работоспособности сценария.
* stop не даёт сигнала в finish_reason: он остаётся stop и со стоп-строкой, и без
  неё. Показывать эффект приходится содержанием, а не статусом.
* Стоп-строка в вывод не попадает — обрыв происходит перед ней.
"""

from __future__ import annotations

from app.schema import Scenario, Session

# Одна модель на все шесть колонок дня. openai/gpt-4o-mini перечисляет
# response_format, max_tokens и stop в supported_parameters, поэтому проходит
# фильтр дропдауна и не отваливается на provider.require_parameters=true,
# который стенд шлёт на каждом вызове.
MODEL = "openai/gpt-4o-mini"

# Единственный вопрос дня: он уходит во все шесть колонок дословно одинаковым.
# Три требования к нему, и каждое обязательное — вопрос подобран так, чтобы
# выполнить их все сразу, а не по одному на сценарий.
#
# 1. Слово «JSON» в тексте. Без него response_format={"type": "json_object"}
#    вернёт 400 на моделях семейства OpenAI, и сценарий day-02-format умрёт.
#    Здесь оно есть естественно — вопрос как раз про JSON и его родственников.
# 2. Длинный свободный ответ (три пункта по 4–6 предложений — заведомо больше
#    сотни токенов). Иначе max_tokens=80 может и не успеть обрезать: обрыв
#    в day-02-length должен быть гарантирован, а не «как повезёт».
# 3. Достижимый маркер «2)» в выводе. На нём стоит стоп-строка day-02-stop.
#    Разметку приходится задавать явно: сама по себе модель оформит список как
#    «1.», «**JSON**» или буллитами — и stop не сработает вообще.
#
# Запрет на вступление важен отдельно: перечисление «разберу 1) JSON, 2) JSON
# Lines, 3) MessagePack» во вводной фразе поймало бы стоп-строку на первой же
# строке ответа, и вместо честного первого пункта справа остался бы огрызок.
QUESTION = (
    "Ты объясняешь junior-бэкендеру форматы обмена данными между сервисами. "
    "Разбери JSON, JSON Lines и MessagePack — по одному пункту на формат, "
    "ровно в этом порядке и ровно с такой нумерацией:\n"
    "1) JSON — как устроен, в каких задачах его выбирают и какая типичная ошибка "
    "ждёт при сериализации больших чисел, дат и null.\n"
    "2) JSON Lines — то же самое про этот формат.\n"
    "3) MessagePack — то же самое про этот формат.\n"
    "Нумеруй пункты именно так: «1)», «2)», «3)», каждый с новой строки. "
    "Не пиши вступления и не перечисляй форматы заранее — сразу начинай с первого "
    "пункта. По каждому формату дай короткий пример. Каждый пункт — 4–6 предложений."
)

MESSAGES = [{"role": "user", "content": QUESTION}]

# Заведомо меньше того, что модель хочет написать на этот вопрос: обрыв
# гарантирован, а не «как повезёт».
LIMIT = 80

# Достижимая стоп-строка: маркер второго пункта. Ответ оборвётся на границе
# между первым и вторым пунктом, самой строки «2)» в выводе не будет.
STOP = ["2)"]

FORMAT = Scenario(
    id="day-02-format",
    title="Формат ответа",
    description=(
        "Одна модель, дословно один и тот же вопрос в обеих колонках. "
        "Левая колонка не задаёт ни одного параметра. Правая добавляет ровно один — "
        "response_format={'type': 'json_object'}; лимита длины здесь нет специально, "
        "чтобы JSON пришёл целым и валидным. "
        "Общий вопрос дня просит пронумерованный разбор, но гарантию даёт только "
        "параметр: справа ответ обязан быть валидным JSON-объектом, а как в нём "
        "окажутся пункты — на усмотрение модели. "
        "Смысл сценария: response_format меняет форму ответа и только форму — "
        "на то, как ответ завершается, он не влияет."
    ),
    watch_for=(
        "Форма: слева ответ приходит обычным текстом — скорее всего пронумерованным "
        "разбором «1)», «2)», «3)», как просил промпт, — справа JSON-объектом. "
        "Вопрос один и тот же, разница только в параметре. Как модель уложит пункты "
        "внутрь объекта — полями, списком или строками с теми же маркерами — "
        "параметр не диктует: он гарантирует валидный JSON, а не конкретную схему. "
        "finish_reason: stop в обеих колонках — формат не про завершение. "
        "JSON справа дописан до закрывающей скобки: лимита нет, обрывать нечему. "
        "Счётчик completion-токенов справа может быть даже больше левого — "
        "структура стоит скобок, кавычек и имён полей."
    ),
    layout="split",
    sessions=[
        Session(
            label="A. Свободный ответ",
            model=MODEL,
            messages=MESSAGES,
            note=(
                "Ни одного параметра запроса: «свободный» здесь — про запрос, а не "
                "про требования к форме. Форму задаёт только промпт, и видно, "
                "насколько модель выполняет его просьбу про пункты «1)», «2)», «3)». "
                "Заканчивает ответ модель сама: finish_reason = stop."
            ),
        ),
        Session(
            label="B. + response_format",
            model=MODEL,
            messages=MESSAGES,
            response_format={"type": "json_object"},
            note=(
                "Единственное отличие — response_format={'type': 'json_object'}. "
                "Тот же вопрос, та же модель, длину никто не ограничивает. "
                "Работает только потому, что слово «JSON» есть в самом промпте."
            ),
        ),
    ],
)

LENGTH = Scenario(
    id="day-02-length",
    title="Ограничение длины",
    description=(
        "Одна модель, дословно один и тот же вопрос в обеих колонках. "
        "Левая колонка не задаёт ни одного параметра. Правая добавляет ровно один — "
        f"max_tokens={LIMIT}; формат ответа не трогаем. "
        f"{LIMIT} токенов заведомо меньше того, что модель хочет написать на этот "
        "вопрос, поэтому обрыв гарантирован, а не «как повезёт». "
        "Смысл сценария: max_tokens — единственный из трёх параметров дня, "
        "который виден сразу по статусу, а не по содержанию."
    ),
    watch_for=(
        "finish_reason: слева stop, справа length — прямой сигнал, что ответ "
        "обрезали снаружи, а не модель закончила сама. Главный кадр дня. "
        f"completion_tokens справа упирается ровно в {LIMIT}, слева в несколько раз больше. "
        "Текст справа обрывается на полуслове, посреди фразы — никакого «в заключение». "
        "Три независимых подтверждения одного ограничения: статус, счётчик и сам текст."
    ),
    layout="split",
    sessions=[
        Session(
            label="A. Свободный ответ",
            model=MODEL,
            messages=MESSAGES,
            note=(
                "Ни одного параметра запроса. Объём задан только просьбой в промпте — "
                "три пункта по 4–6 предложений, — и модель дописывает ответ до конца "
                "сама: finish_reason = stop. Просьбу можно выполнить или не выполнить; "
                "справа тот же объём режут снаружи, не спрашивая."
            ),
        ),
        Session(
            label="B. + max_tokens",
            model=MODEL,
            messages=MESSAGES,
            max_tokens=LIMIT,
            note=(
                f"Единственное отличие — max_tokens={LIMIT}. Генерацию обрывают жёстко "
                "по счётчику токенов: finish_reason = length, фраза оборвана на полуслове."
            ),
        ),
    ],
)

STOP_SCENARIO = Scenario(
    id="day-02-stop",
    title="Условие завершения",
    description=(
        "Одна модель и тот же общий вопрос дня, что в двух других сценариях: "
        "разобрать три формата обмена данными пунктами «1)», «2)», «3)». "
        "Левая колонка не задаёт ни одного параметра. Правая добавляет ровно один — "
        "stop=['2)'], то есть стоп-строкой стоит маркер второго пункта. "
        "Нумерацию общий вопрос задаёт явно именно ради этого сценария: оформи "
        "модель список по-своему, маркер не встретится и параметр не сработает вообще. "
        "Смысл сценария: stop отработает — и не оставит следа в статусе ответа."
    ),
    watch_for=(
        "Содержание: слева три пункта, справа ответ обрывается на границе после "
        "первого — второго и третьего просто нет. "
        "Самой стоп-строки «2)» в выводе НЕТ: обрыв происходит перед ней, "
        "провайдер её не отдаёт. "
        "finish_reason: stop в ОБЕИХ колонках — статус одинаков и там, где модель "
        "договорила сама, и там, где её остановила стоп-строка. "
        "Это и есть урок дня: параметр сработал, а по статусу этого не понять — "
        "только по длине и содержанию. Сравните с day-02-length, где max_tokens "
        "заявляет о себе сразу: finish_reason = length."
    ),
    layout="split",
    sessions=[
        Session(
            label="A. Свободный ответ",
            model=MODEL,
            messages=MESSAGES,
            note=(
                "Ни одного параметра запроса. Модель проходит все три пункта — "
                "«1)», «2)», «3)» — и заканчивает сама: finish_reason = stop."
            ),
        ),
        Session(
            label="B. + stop",
            model=MODEL,
            messages=MESSAGES,
            stop=STOP,
            note=(
                "Единственное отличие — stop=['2)']. Генерация останавливается, "
                "как только модель начинает второй пункт: остаётся только первый, "
                "маркера «2)» в выводе нет, а finish_reason всё тот же stop."
            ),
        ),
    ],
)

# Порядок значим: он задаёт порядок в сайдбаре и совпадает с порядком, в каком
# параметры перечислены в задании дня — response_format, max_tokens, stop.
SCENARIOS = [FORMAT, LENGTH, STOP_SCENARIO]
