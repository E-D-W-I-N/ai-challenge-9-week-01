"""День 04 — одна модель, один промпт, три температуры.

Три колонки отличаются ровно одним числом: temperature = 0.0 / 0.7 / 1.2.
У каждой repeats=5, стенд сам считает долю уникальных ответов по точному
совпадению текста после strip(). Ожидаемая картина — доля растёт слева направо.

Почему промпт такой, какой он есть:
  * задача открытая (название кофейни), допустимых ответов много — на фактическом
    вопросе даже t=1.2 вернул бы одно и то же и день показал бы пустоту;
  * ответ — одна короткая строка: пять прогонов на колонку × три колонки = 15
    вызовов, длинный ответ превратил бы запись в ожидание;
  * формат зажат до предела (без преамбул, кавычек и точки в конце) — уникальность
    считается по точному совпадению строки, и одно «Конечно! Вот вариант:» сделало
    бы уникальными все пять ответов в каждой колонке, включая t=0.

Модель по умолчанию — не anthropic/*: это семейство обрезает температуру на 1.0
и вернуло бы 400 на колонке t=1.2. Из дропдауна стенд их убирает сам (в сценарии
есть температура выше 1.0), но дефолт обязан быть безопасным.

seed сознательно НЕ фиксируется: один и тот же seed на всех прогонах схлопнул бы
и колонку t=1.2 к одному ответу, то есть убил бы ровно тот эффект, ради которого
день снимается.
"""

from app.schema import Scenario, Session

MODEL = "openai/gpt-4o-mini"

SYSTEM = (
    "Ты отвечаешь ровно одной строкой. Без преамбул, без пояснений, "
    "без кавычек, без нумерации, без точки в конце. Только сам ответ."
)

USER = "Придумай название для кофейни на маяке. Два-три слова, по-русски."


def _messages() -> list[dict]:
    """Один и тот же промпт для всех трёх колонок — различие только в temperature."""
    return [
        {"role": "system", "content": SYSTEM},
        {"role": "user", "content": USER},
    ]


# Не даём OpenRouter уводить повторы к разным провайдерам: маршрутизация — это
# отдельный источник разброса, и без этой строчки колонка t=0 могла бы показать
# 5 уникальных из 5 не из-за температуры. Детерминизма это не даёт, только убирает
# один посторонний фактор. Плата за это — прогон упадёт, если основной провайдер
# модели недоступен, фолбэка не будет.
PIN_PROVIDER = {"provider": {"allow_fallbacks": False}}

# Одна короткая строка укладывается в ~10 токенов. 64 — запас, чтобы ни один из
# 15 прогонов не оборвался на finish_reason: length (это эффект Дня 2, здесь он
# только запутал бы картину).
MAX_TOKENS = 64

REPEATS = 5


SCENARIO = Scenario(
    id="day-04",
    title="День 4 — temperature 0 / 0.7 / 1.2 и доля уникальных ответов",
    description=(
        "Одна модель, один промпт, пять прогонов в каждой колонке. Отличается "
        "ровно одно число — temperature: 0.0, 0.7, 1.2. Задача открытая "
        "(придумать название кофейни), правильных ответов много, ответ — одна "
        "короткая строка. Стенд считает долю уникальных ответов на колонку по "
        "точному совпадению текста."
    ),
    watch_for=(
        "Строка «уникальных ответов: N из 5» под каждой колонкой. Слева направо "
        "доля растёт: при t=0 повторы в основном совпадают, при t=0.7 появляется "
        "разнобой, при t=1.2 совпадений почти нет, а формулировки становятся "
        "вычурнее. Важно: единица из пяти при t=0 не гарантирована — T=0 на "
        "OpenRouter не равен детерминизму, подробности в day-04/README.md."
    ),
    layout="split",
    sessions=[
        Session(
            label="t = 0.0",
            model=MODEL,
            messages=_messages(),
            temperature=0.0,
            max_tokens=MAX_TOKENS,
            repeats=REPEATS,
            extra_body=PIN_PROVIDER,
            note=(
                "Жадное декодирование: на каждом шаге берётся самый вероятный "
                "токен. Повторы должны совпадать чаще всего — но «чаще всего» "
                "это не «всегда»."
            ),
        ),
        Session(
            label="t = 0.7",
            model=MODEL,
            messages=_messages(),
            temperature=0.7,
            max_tokens=MAX_TOKENS,
            repeats=REPEATS,
            extra_body=PIN_PROVIDER,
            note=(
                "Рабочий режим по умолчанию у большинства чат-моделей. "
                "Разброс есть, ответы остаются осмысленными."
            ),
        ),
        Session(
            label="t = 1.2",
            model=MODEL,
            messages=_messages(),
            temperature=1.2,
            max_tokens=MAX_TOKENS,
            repeats=REPEATS,
            extra_body=PIN_PROVIDER,
            note=(
                "Распределение сплющено, у хвоста появляется шанс. Уникальных "
                "ответов больше всего, вместе с разбросом растёт и риск "
                "вычурных или кривых формулировок."
            ),
        ),
    ],
)
