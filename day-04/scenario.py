"""День 04 — одна модель, один промпт, три температуры: 0.0 / 0.7 / 1.2.

Три колонки отличаются ровно одним числом. Повторов нет: один прогон на колонку,
день сравнительный, а не бенчмарк.

Раз повторов нет, нет и доли уникальных ответов — считать не по чему. Разброс
должен читаться в самом тексте, поэтому промпт просит пять названий в одном
ответе. Тогда разнообразие видно дважды: внутри колонки (насколько пять строк
похожи друг на друга) и между колонками (насколько списки отличаются).

Почему промпт такой, какой он есть:
  * задача открытая (название пекарни), одинаково допустимых ответов много —
    на фактическом вопросе три колонки вернули бы одно и то же и день показал бы
    пустоту;
  * пять коротких строк вместо одной: разброс виден без счётчиков;
  * жёсткого «ровно одна строка, без точки в конце» больше нет — оно было нужно
    только для подсчёта уникальности по точному совпадению. Из формата остались
    два ограничения, которые делают колонки сравнимыми взглядом: строка на
    вариант и 1–3 слова.

Модель по умолчанию — не anthropic/*: это семейство обрезает температуру на 1.0
и вернуло бы 400 на колонке t=1.2. Из дропдауна стенд их убирает сам (в сценарии
есть температура выше 1.0), но дефолт обязан быть безопасным и без дропдауна.

seed сознательно НЕ фиксируется: он ничего не добавил бы к сравнению трёх разных
температур в трёх разных вызовах.
"""

from app.schema import Scenario, Session

MODEL = "openai/gpt-4o-mini"

PROMPT = (
    "Придумай 5 названий для маленькой пекарни, которая работает только ночью.\n"
    "Каждое — отдельной строкой, 1–3 слова, без пояснений и без нумерации."
)


def _messages() -> list[dict]:
    """Один и тот же промпт для всех трёх колонок — различие только в temperature."""
    return [{"role": "user", "content": PROMPT}]


# Три колонки должны отличаться температурой и ничем больше. Без этой строчки
# OpenRouter вправе увести соседние колонки к разным провайдерам — с другой
# квантизацией и другой версией рантайма, — и часть разницы в текстах пришла бы
# не от температуры. Плата: прогон упадёт, если основной провайдер модели
# недоступен, тихого фолбэка не будет.
PIN_PROVIDER = {"provider": {"allow_fallbacks": False}}

# Пять строк по 1–3 слова — это ~40 токенов. 120 берём с запасом, чтобы список
# не оборвался на середине: обрыв по длине — эффект Дня 2, здесь он только
# запутал бы картину.
MAX_TOKENS = 120


SCENARIOS = [
    Scenario(
        id="day-04-temperature",
        title="temperature 0 / 0.7 / 1.2",
        description=(
            "Одна модель, один промпт, один прогон на колонку. Отличается ровно "
            "одно число — temperature: 0.0, 0.7, 1.2. Задача открытая: пять "
            "названий для ночной пекарни. Правильных ответов много, поэтому "
            "температуре есть где проявиться — на фактическом вопросе все три "
            "колонки вернули бы одно и то же."
        ),
        watch_for=(
            "Читайте пять строк внутри каждой колонки, а потом сравнивайте колонки "
            "между собой. Слева пятёрка обычно однотипная — общий корень, одна "
            "метафора, вариации одного и того же названия. В середине появляется "
            "разнобой при сохранении осмысленности. Справа варианты разнородные и "
            "неожиданные, иногда кривые: сломанное согласование, редкое слово не к "
            "месту. Счётчиков в этом сценарии нет, разница читается взглядом. "
            "Важно: t=0 — это не детерминизм. Варианты предсказуемее и однороднее, "
            "но повторяемость между запусками не гарантирована, так что второй "
            "прогон левой колонки может дать другой список. Подробности в "
            "day-04/README.md."
        ),
        layout="split",
        sessions=[
            Session(
                label="t = 0.0",
                model=MODEL,
                messages=_messages(),
                temperature=0.0,
                max_tokens=MAX_TOKENS,
                extra_body=PIN_PROVIDER,
                note=(
                    "Жадное декодирование: на каждом шаге берётся самый вероятный "
                    "токен. Пять названий получаются близкими друг к другу — "
                    "модель идёт по одной и той же самой вероятной ассоциации."
                ),
            ),
            Session(
                label="t = 0.7",
                model=MODEL,
                messages=_messages(),
                temperature=0.7,
                max_tokens=MAX_TOKENS,
                extra_body=PIN_PROVIDER,
                note=(
                    "Рабочий режим по умолчанию у большинства чат-моделей. "
                    "Внутри пятёрки появляется разнобой, ответы остаются "
                    "осмысленными."
                ),
            ),
            Session(
                label="t = 1.2",
                model=MODEL,
                messages=_messages(),
                temperature=1.2,
                max_tokens=MAX_TOKENS,
                extra_body=PIN_PROVIDER,
                note=(
                    "Распределение сплющено, у хвоста появляется шанс. Названия "
                    "разнородные и неожиданные — вместе с разнообразием растёт "
                    "риск вычурных и просто кривых формулировок."
                ),
            ),
        ],
    ),
]
