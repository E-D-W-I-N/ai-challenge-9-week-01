"""День 04 — одна модель, один промпт, три температуры: 0.0 / 0.7 / 1.2.

Три колонки отличаются ровно одним числом, и в каждой repeats=3: три прогона
одного и того же запроса. Девять вызовов за сценарий.

Повторы здесь не роскошь, а условие работоспособности дня. Температура —
свойство статистическое: она задаёт, насколько широко модель сэмплирует из
распределения, и на одном ответе этого не увидеть. Дважды день снимали с одним
вызовом на колонку, и оба раза заказчик говорил одно и то же: разницы между
температурами не видно. Правильный ответ на это — не хитрее промпт, а выборка.
Три прогона дают её напрямую, а стенд считает под колонкой долю уникальных
ответов.

Отсюда требования к промпту, и они противоположны прежним. Раньше нужен был
ответ, внутри которого виден разброс (восемь ассоциаций плюс проверяемый факт).
Теперь разброс считается МЕЖДУ прогонами, а сам ответ должен быть коротким и
сравнимым: уникальность стенд определяет точным совпадением текста после
strip(), так что любая болтовня вокруг ответа портит счётчик. Поэтому формат
зажат до двух строк без преамбул и нумерации.

Ответ устроен так, чтобы день по-прежнему показывал все три оси задания:

  * первая строка — название кофейни на маяке. Задача открытая, одинаково
    допустимых ответов много: отсюда и разнообразие (совпадают ли три прогона),
    и креативность (насколько названия неожиданны);
  * вторая строка — год выхода первого iPhone. Правильный ответ ровно один и
    общеизвестен. Это опора: видно, чем платят за разнообразие, когда на t=1.2
    вместе с фантазией разъезжается и факт.

Первая строка даёт счётчику уникальности почти всю его работу: год при любой
температуре чаще один и тот же, а название — то, что реально расходится.

Модель по умолчанию — не anthropic/*: это семейство обрезает температуру на 1.0
и вернуло бы 400 на колонке t=1.2. Из дропдауна стенд их убирает сам (в сценарии
есть температура выше 1.0), но дефолт обязан быть безопасным и без дропдауна.

Рассуждающие модели дропдаун НЕ убирает (фильтр смотрит только на temperature,
:free и anthropic/*), а температуру они игнорируют молча — переключать на них
колонку во время записи нельзя. В дропдауне этого дня они составляют
большинство: 167 моделей из 278. По имени они не опознаются: у deepseek-r1 и
gemini-*-flash нет -thinking в id, а o-серия OpenAI, наоборот, до дропдауна
этого дня не доходит — она не заявляет temperature. Надёжный признак — reasoning
в supported_parameters; список проверенно чистых моделей и разбор —
в day-04/README.md.

seed сознательно НЕ фиксируется. С повторами это уже не мелочь: один seed на всю
серию схлопнул бы колонку t=1.2 к одному ответу, то есть убил бы ровно тот
эффект, ради которого день снимается.
"""

from app.schema import Scenario, Session

MODEL = "openai/gpt-4o-mini"

PROMPT = (
    "Ответь ровно двумя строками, без пояснений и без нумерации.\n"
    "Строка 1: название для кофейни на маяке — 1–3 слова.\n"
    "Строка 2: год выхода первого iPhone — только число."
)


def _messages() -> list[dict]:
    """Один и тот же промпт для всех трёх колонок — различие только в temperature."""
    return [{"role": "user", "content": PROMPT}]


# Три колонки должны отличаться температурой и ничем больше. Без этой строчки
# OpenRouter вправе увести соседние колонки — и соседние прогоны одной колонки —
# к разным провайдерам, с другой квантизацией и другой версией рантайма. Тогда
# часть разброса придёт не от температуры, а уникальность в колонке t=0 вырастет
# просто потому, что три прогона обслужили разные машины. Плата: прогон упадёт,
# если основной провайдер модели недоступен, тихого фолбэка не будет.
PIN_PROVIDER = {"provider": {"allow_fallbacks": False}}

# Две короткие строки — это ~15 токенов. 80 берём с запасом на t=1.2, где модель
# охотнее добавляет лишнее. Обрыв по длине — эффект Дня 2, здесь он только
# запутал бы, а ещё испортил бы счётчик: обрезанный ответ отличается от целого
# и считается уникальным.
MAX_TOKENS = 80

# Три прогона на колонку. Меньше — выборки нет, доля уникальных вырождается
# в «одинаково / по-разному». Больше — девять вызовов превращаются в
# двенадцать и пятнадцать, а картина уже читается. Цена растёт кратно.
REPEATS = 3


SCENARIOS = [
    Scenario(
        id="day-04-temperature",
        title="temperature 0 / 0.7 / 1.2",
        description=(
            "Одна модель, один промпт, три прогона в каждой колонке. Отличается "
            "ровно одно число — temperature: 0.0, 0.7, 1.2. Ответ короткий и "
            "жёстко форматированный: первая строка — придуманное название "
            "кофейни на маяке, вторая — год выхода первого iPhone. Под каждой "
            "колонкой стенд считает долю уникальных ответов по трём прогонам: "
            "это и есть мера разброса, которую даёт температура."
        ),
        watch_for=(
            "Главное в кадре — строка «уникальных ответов: N из 3» под каждой "
            "колонкой. Слева она обычно 1 из 3, справа 3 из 3, посередине "
            "как получится. Рядом смотрите на сами прогоны: слева три "
            "одинаковых названия, справа три разных и заметно более вычурных, "
            "иногда с нарушенным форматом. Вторая строка — проверка на "
            "точность: эталон 2007, и именно справа выше шанс увидеть другой "
            "год или лишние слова вместо голого числа. Разнообразие и ошибки "
            "растут вместе, это одна ручка, а не две. "
            "Честная оговорка, которую стоит произнести вслух: 1 из 3 при t=0 "
            "вероятна, но не гарантирована — T=0 на OpenRouter не даёт "
            "детерминизма. Увидели 2 из 3 слева — это не поломка сценария, "
            "разбор в day-04/README.md. "
            "И не переключайте колонку на рассуждающую модель: они игнорируют "
            "temperature молча, и день покажет неправду. В дропдауне Дня 04 "
            "такие модели — большинство, и по имени они не опознаются, так что "
            "выбирайте из проверенных: openai/gpt-4o-mini (уже стоит), "
            "meta-llama/llama-3.1-8b-instruct, "
            "mistralai/mistral-small-3.2-24b-instruct. Любая другая — сначала "
            "reasoning в её supported_parameters."
        ),
        layout="split",
        # Пункты задания Дня 4: «сравните ответы по точности, креативности,
        # разнообразию» — три оси, по вопросу на каждую, — и «сформулируйте,
        # для каких задач лучше подходит каждая настройка».
        #
        # Судья видит все три прогона каждой колонки и долю уникальных, поэтому
        # первый вопрос спрашивает именно про серию, а не про один ответ.
        #
        # Эталон фактической строки судье намеренно не сообщается — ни здесь,
        # ни в description, который стенд отправляет ему вместе с вопросами.
        # Год общеизвестен, судья крупнее подопытных: пусть проверит сам, иначе
        # вопрос про точность проверяет не модель, а нас. (watch_for судье
        # не уходит, там эталон назван прямо — это подсказка ведущему.)
        judge_questions=[
            "Насколько три прогона внутри каждой колонки похожи друг на друга "
            "и как доля уникальных ответов меняется от колонки к колонке?",
            "Что стоит во второй строке каждого прогона и какие из этих "
            "ответов на фактический вопрос верны?",
            "Насколько предсказуемы или неожиданны названия в первой строке "
            "и встречаются ли среди них бессмысленные или ломающие формат?",
            "Для каких задач подходит каждая из трёх температур, если судить "
            "по тому, что вышло в колонках?",
        ],
        sessions=[
            Session(
                label="t = 0.0",
                model=MODEL,
                messages=_messages(),
                temperature=0.0,
                max_tokens=MAX_TOKENS,
                repeats=REPEATS,
                extra_body=PIN_PROVIDER,
                note=(
                    "Жадное декодирование: на каждом шаге берётся самый "
                    "вероятный токен. Три прогона должны совпасть — но "
                    "«должны» тут не значит «обязаны»."
                ),
            ),
            Session(
                label="t = 0.7",
                model=MODEL,
                messages=_messages(),
                temperature=0.7,
                max_tokens=MAX_TOKENS,
                repeats=REPEATS,
                extra_body=PIN_PROVIDER,
                note=(
                    "Рабочий режим по умолчанию у большинства чат-моделей. "
                    "Названия расходятся, факт обычно ещё держится."
                ),
            ),
            Session(
                label="t = 1.2",
                model=MODEL,
                messages=_messages(),
                temperature=1.2,
                max_tokens=MAX_TOKENS,
                repeats=REPEATS,
                extra_body=PIN_PROVIDER,
                note=(
                    "Распределение сплющено, у хвоста появляется шанс. Три "
                    "разных названия почти наверняка — и ровно здесь вторая "
                    "строка рискует поехать."
                ),
            ),
        ],
    ),
]
