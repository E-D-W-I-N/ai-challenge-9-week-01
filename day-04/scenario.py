"""День 04 — одна модель, один промпт, три температуры: 0.0 / 0.7 / 1.2.

Три колонки отличаются ровно одним числом. На каждую колонку приходится ровно
один вызов модели: день сравнительный, а не бенчмарк.

Отсюда главное требование к промпту: температура должна быть видна ВНУТРИ одного
ответа. Прежний промпт («придумай 5 названий для ночной пекарни») этого не давал.
Разброс от температуры — эффект статистический, а пять выдуманных названий на
t=0 и на t=1.2 одинаково выглядят «креативными»: сравнивать не с чем, опорной
точки в кадре нет. На живом прогоне разница между колонками не читалась.

Нынешний промпт даёт опорную точку. Он состоит из двух частей:

  * восемь ассоциаций к многозначному слову — выборка внутри одного ответа.
    Слово «ключ» держит минимум четыре разных смысла (замок, гаечный ключ,
    родник, скрипичный ключ, ключ к разгадке, ключ шифрования), так что
    расходиться есть куда: на t=0 модель берёт самые частотные ассоциации,
    дальше в списке появляются редкие;
  * одна проверяемая фактическая строка в конце — год выпуска первого iPhone,
    2007. Правильный ответ ровно один, и он общеизвестен. Это и есть опора:
    справа от неё видно, чем платят за разнообразие.

В кадре поэтому сразу три оси: разнообразие (по списку), точность (по последней
строке) и креативность (по характеру ассоциаций).

Модель по умолчанию — не anthropic/*: это семейство обрезает температуру на 1.0
и вернуло бы 400 на колонке t=1.2. Из дропдауна стенд их убирает сам (в сценарии
есть температура выше 1.0), но дефолт обязан быть безопасным и без дропдауна.

Рассуждающие модели дропдаун НЕ убирает (фильтр смотрит только на temperature,
:free и anthropic/*), а температуру они игнорируют молча — переключать на них
колонку во время записи нельзя. По имени они не опознаются: у deepseek-r1 и
gemini-*-flash нет -thinking в id, а o-серия OpenAI, наоборот, до дропдауна
этого дня не доходит — она не заявляет temperature. Надёжный признак — reasoning
в supported_parameters; разбор в day-04/README.md.

seed сознательно НЕ фиксируется: он ничего не добавил бы к сравнению трёх разных
температур в трёх разных вызовах.
"""

from app.schema import Scenario, Session

MODEL = "openai/gpt-4o-mini"

PROMPT = (
    "Напиши 8 ассоциаций к слову «ключ» — по одной на строку, "
    "без пояснений и без нумерации.\n"
    "Девятой строкой ответь на вопрос: в каком году вышел первый iPhone? "
    "В этой строке — только год."
)


def _messages() -> list[dict]:
    """Один и тот же промпт для всех трёх колонок — различие только в temperature."""
    return [{"role": "user", "content": PROMPT}]


# Три колонки должны отличаться температурой и ничем больше. Без этой строчки
# OpenRouter вправе увести соседние колонки к разным провайдерам — с другой
# квантизацией и другой версией рантайма, — и часть разницы в текстах пришла бы
# не от температуры. Плата: прогон упадёт, если основной провайдер модели
# недоступен, тихого фолбэка не будет.
PIN_PROVIDER = {"provider": {"allow_fallbacks": False}}

# Девять коротких строк — это ~60 токенов. 200 берём с запасом на t=1.2: там
# модель охотнее уходит в лишние слова, а оборваться ответ не должен ни в одной
# колонке. Обрыв по длине — эффект Дня 2, здесь он только запутал бы картину,
# и хуже того — съел бы фактическую строку, ради которой промпт и написан.
MAX_TOKENS = 200


SCENARIOS = [
    Scenario(
        id="day-04-temperature",
        title="temperature 0 / 0.7 / 1.2",
        description=(
            "Одна модель, один промпт, один вызов на колонку. Отличается ровно "
            "одно число — temperature: 0.0, 0.7, 1.2. Промпт из двух частей: "
            "восемь ассоциаций к многозначному слову «ключ» и девятой строкой — "
            "год выпуска первого iPhone. Список показывает разнообразие внутри "
            "одного ответа, фактическая строка даёт опорную точку с единственным "
            "правильным ответом: 2007."
        ),
        watch_for=(
            "Смотрите на каждую колонку сверху вниз, а потом сравнивайте колонки "
            "между собой по трём вещам. Первое — ассоциации: слева самые "
            "частотные и предсказуемые (замок, дверь, связка), в середине "
            "появляется разнобой, справа всплывают редкие и неожиданные смыслы "
            "многозначного слова, а иногда и просто мусор. Второе — девятая "
            "строка: правильный ответ 2007, и именно справа выше шанс увидеть "
            "неверный год или лишние слова вместо голого числа. Третье — цена: "
            "разнообразие и ошибки растут вместе, это одна ручка, а не две. "
            "Собственной метрики у этого дня нет: панель под колонками — общая "
            "для стенда, и в этом дне она ничего не решает, разница читается "
            "взглядом. Важно: t=0 — это не детерминизм, повторяемость между "
            "запусками не гарантирована. И не переключайте колонку на "
            "рассуждающую модель: они игнорируют temperature молча, и день "
            "покажет неправду. По имени такие модели не опознать — в дропдауне "
            "Дня 04 это deepseek-r1, всё с -thinking, и вся линейка "
            "gemini-*-flash; признак надёжнее — reasoning в "
            "supported_parameters. Безопасны gpt-4o*, meta-llama/*, "
            "mistralai/*. Подробности в day-04/README.md."
        ),
        layout="split",
        sessions=[
            Session(
                label="t = 0.0",
                model=MODEL,
                messages=_messages(),
                temperature=0.0,
                max_tokens=MAX_TOKENS,
                extra_body=PIN_PROVIDER,
                note=(
                    "Жадное декодирование: на каждом шаге берётся самый вероятный "
                    "токен. Ассоциации — из верхушки частотного списка, "
                    "фактическая строка почти наверняка верна."
                ),
            ),
            Session(
                label="t = 0.7",
                model=MODEL,
                messages=_messages(),
                temperature=0.7,
                max_tokens=MAX_TOKENS,
                extra_body=PIN_PROVIDER,
                note=(
                    "Рабочий режим по умолчанию у большинства чат-моделей. "
                    "В списке появляется разнобой, факт обычно ещё держится."
                ),
            ),
            Session(
                label="t = 1.2",
                model=MODEL,
                messages=_messages(),
                temperature=1.2,
                max_tokens=MAX_TOKENS,
                extra_body=PIN_PROVIDER,
                note=(
                    "Распределение сплющено, у хвоста появляется шанс. "
                    "Ассоциации самые неожиданные — и ровно здесь фактическая "
                    "строка рискует поехать."
                ),
            ),
        ],
    ),
]
