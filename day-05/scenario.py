#   1) «брать по убыванию оплаты»: C, E, B → 15 400 ₽. Недобор 500.
#      Тот же набор даёт и жадность по оплате за минуту — то есть две из трёх
#      естественных жадных стратегий садятся ровно сюда.
#   2) «брать по убыванию оплаты за килограмм»: B, A, D, F → 14 900 ₽.
#      Недобор 1000.
# Оптимум забивает лимит веса ровно под завязку (100 из 100) и ни с одной
# из жадных выборок не совпадает: чтобы его найти, надо перебирать,
# а не сортировать.
#
# Эталона нет ни в description, ни в note колонок: стенд отдаёт эти два поля
