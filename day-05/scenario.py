# ── Задача и эталон ─────────────────────────────────────────────────────────
#
# Ежемесячные затраты (q — этикеток в месяц):
#   А = 15 000 + 1,20q
#   Б = 20 000 (амортизация 480 000 / 24) + 6 000 (обслуживание) + 0,65q
#     = 26 000 + 0,65q
# Зарплата операторов 3 × 60 000 одинакова в обоих вариантах и в сравнение
# не входит — она есть и там, и там, на разницу не влияет.
#
# Точка равенства: 15 000 + 1,2q = 26 000 + 0,65q → 0,55q = 11 000 → q = 20 000.
#
# Объём: месяц 1 — 14 000, дальше +2 000 в месяц. 20 000 приходится ровно
# на 4-й месяц (там варианты равны), значит ежемесячно Б дешевле с 5-го месяца.
#
# Накопленная разница (А − Б) по месяцам:
#   м1 −3 300, м2 −5 500, м3 −6 600, м4 −6 600, м5 −5 500, м6 −3 300, м7 0.
# На 7-м месяце обнуляется, значит накопительно Б выгоднее с 8-го месяца.
#
# Эталонный ответ целиком:
#   ТОЧКА РАВЕНСТВА: 20000
#   ЕЖЕМЕСЯЧНО ВЫГОДНЕЕ С: 5
#   НАКОПИТЕЛЬНО ВЫГОДНЕЕ С: 8
#
# Три ловушки:
#   1) зарплата операторов — одинакова в обоих вариантах, в расчёт не входит;
#   2) амортизация — 20 000 ₽/мес, а не 480 000 ₽ разом в первый месяц;
#   3) «ежемесячно» и «накопительно» дают разные месяцы (5 и 8) — модель,
#      нашедшая первый переход, обычно принимает его за ответ и ставит 5 в обе
#      строки. Это главный разделитель между ступенями.

SYSTEM = (
    "Ты — расчётный модуль финансового отдела. Ты выдаёшь только результат "
    "в заданном формате: без приветствий, без пояснений, без markdown, "
    "без пустых строк, без текста до и после."
)

TASK = """Типография выбирает, как печатать этикетки.

Вариант А: аренда принтера 15 000 ₽/мес, расходники 1,20 ₽ за этикетку.
Вариант Б: покупка за 480 000 ₽ с равномерной амортизацией на 24 месяца,
обслуживание 6 000 ₽/мес, расходники 0,65 ₽ за этикетку.
В цехе 3 оператора с зарплатой 60 000 ₽ — они нужны при любом варианте.
Объём в первый месяц 14 000 этикеток, дальше растёт на 2 000 этикеток каждый месяц.

Определи:
1) точку равенства — при каком месячном объёме этикеток затраты по варианту А
   и по варианту Б за месяц равны;
2) первый месяц, начиная с которого затраты за сам этот месяц по варианту Б
   строго меньше, чем по варианту А;
3) первый месяц, начиная с которого суммарные затраты с первого месяца
   по этот включительно по варианту Б строго меньше, чем по варианту А.

Месяцы нумеруются с 1. Ответ — ровно три строки, ни строкой больше:
ТОЧКА РАВЕНСТВА: <этикеток в месяц>
ЕЖЕМЕСЯЧНО ВЫГОДНЕЕ С: <номер месяца>
НАКОПИТЕЛЬНО ВЫГОДНЕЕ С: <номер месяца>

Единицы измерения, знак рубля, слово «месяц» и пробелы внутри чисел не пиши —
только целые числа."""

MESSAGES = [
    {"role": "system", "content": SYSTEM},
    {"role": "user", "content": TASK},
]

# Одинаково во всех трёх колонках: разницу должна давать только модель.
TEMPERATURE = 0.2
MAX_TOKENS = 3000  # задача многошаговая, сильная ступень может расписывать расчёт

# Без него OpenRouter вправе увести запрос к другому провайдеру, и станет
# непонятно, чью задержку и чью цену мы измерили.
NO_FALLBACKS = {"provider": {"allow_fallbacks": False}}


def rung(label: str, model: str, note: str) -> Session:
    """Ступень лестницы. Отличается от соседней только полем model."""
    return Session(
        label=label,
        model=model,
        messages=MESSAGES,
        temperature=TEMPERATURE,
        max_tokens=MAX_TOKENS,
        note=note,
        extra_body=NO_FALLBACKS,
    )


