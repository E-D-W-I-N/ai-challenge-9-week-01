TASK = """Курьерская служба формирует смену. Есть шесть заказов:

Заказ A: вес 30 кг, время 90 мин, оплата 5000 ₽
Заказ B: вес 25 кг, время 60 мин, оплата 4200 ₽
Заказ C: вес 40 кг, время 80 мин, оплата 6000 ₽
Заказ D: вес 20 кг, время 50 мин, оплата 3300 ₽
Заказ E: вес 35 кг, время 70 мин, оплата 5200 ₽
Заказ F: вес 15 кг, время 40 мин, оплата 2400 ₽

Машина везёт не больше 100 кг, смена длится не больше 240 минут.
Заказы берутся целиком — часть заказа взять нельзя.

Какой набор заказов даёт максимальную выручку?

Отвечай обычным текстом, без markdown: без звёздочек, решёток, маркеров списка
и таблиц из вертикальных палочек. Структура ответа — ровно такая и в таком порядке:

РАЗБОР
Наборы, которые ты рассматривал, по одной строке на набор, каждая в таком виде:
<буквы заказов через запятую>: вес <кг>; время <мин>; выручка <руб>; <вердикт>
В вердикте — либо почему набор отброшен (какой лимит нарушен или чем он хуже
другого), либо что он остаётся кандидатом. Наборы, нарушающие лимиты, тоже
показывай.

РЕКОМЕНДАЦИЯ
Одно-два предложения простым языком для диспетчера, без формул: что ставить
в смену.

Последними — ровно четыре строки, каждая с начала строки, и ничего после них:
НАБОР: <буквы заказов через запятую>
ВЫРУЧКА: <число>
ВЕС: <число>
ВРЕМЯ: <число>

В этих четырёх строках — только буквы заказов и целые числа: без единиц
измерения, без знака рубля и без пробелов внутри чисел."""

MESSAGES = [
    {"role": "system", "content": SYSTEM},
    {"role": "user", "content": TASK},
]

# Одинаково во всех трёх колонках: разницу должна давать только модель.
TEMPERATURE = 0.2

# Запас на самую многословную ступень. Перебор многословнее прежнего расчёта
# затрат: добросовестная колонка выписывает десятки наборов по строке на каждый,
# а сильная ступень докладывает сверху reasoning, который тоже считается в лимит.
# Обрыв по max_tokens исказил бы сравнение сильнее, чем щедрый лимит: колонка
# с finish_reason=length теряет и машиночитаемый хвост, и хвост разбора.
MAX_TOKENS = 8000

# Без него OpenRouter вправе увести запрос к другому провайдеру, и станет
# непонятно, чью задержку и чью цену мы измерили.
NO_FALLBACKS = {"provider": {"allow_fallbacks": False}}


def rung(label: str, model: str, note: str) -> Session:
    """Ступень лестницы. Отличается от соседней только полем model."""
    return Session(
        label=label,
        model=model,
        messages=MESSAGES,
        temperature=TEMPERATURE,
        max_tokens=MAX_TOKENS,
        note=note,
        extra_body=NO_FALLBACKS,
    )


