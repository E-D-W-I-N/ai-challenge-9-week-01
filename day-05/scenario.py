"""День 05 — одна задача, три ступени моделей: latency, токены и cost рядом.

Три колонки различаются ровно одним полем — `model`. Промпт, `temperature`,
`max_tokens` совпадают, иначе разницу в цифрах нельзя приписать модели.

Каждая колонка — ровно один вызов модели. Это сравнительный анализ
качества и цены, а не бенчмарк задержки.

Модель отвечает разбором: расчёт по шагам, рекомендация заказчику и три
машиночитаемые строки в конце. Три строки — ось проверки правильности,
разбор — материал, по которому видна сила модели.
"""

from __future__ import annotations

from app.schema import Scenario, Session

# ── Задача и эталон ─────────────────────────────────────────────────────────
#
# Ежемесячные затраты (q — этикеток в месяц):
#   А = 15 000 + 1,20q
#   Б = 20 000 (амортизация 480 000 / 24) + 6 000 (обслуживание) + 0,65q
#     = 26 000 + 0,65q
# Зарплата операторов 3 × 60 000 одинакова в обоих вариантах и в сравнение
# не входит — она есть и там, и там, на разницу не влияет.
#
# Точка равенства: 15 000 + 1,2q = 26 000 + 0,65q → 0,55q = 11 000 → q = 20 000.
#
# Объём: месяц 1 — 14 000, дальше +2 000 в месяц. 20 000 приходится ровно
# на 4-й месяц (там варианты равны), значит ежемесячно Б дешевле с 5-го месяца.
#
# Накопленная разница (А − Б) по месяцам:
#   м1 −3 300, м2 −5 500, м3 −6 600, м4 −6 600, м5 −5 500, м6 −3 300, м7 0.
# На 7-м месяце обнуляется, значит накопительно Б выгоднее с 8-го месяца.
#
# Эталонный ответ трёх последних строк:
#   ТОЧКА РАВЕНСТВА: 20000
#   ЕЖЕМЕСЯЧНО ВЫГОДНЕЕ С: 5
#   НАКОПИТЕЛЬНО ВЫГОДНЕЕ С: 8
#
# Три ловушки:
#   1) зарплата операторов — одинакова в обоих вариантах, в расчёт не входит;
#   2) амортизация — 20 000 ₽/мес, а не 480 000 ₽ разом в первый месяц;
#   3) «ежемесячно» и «накопительно» дают разные месяцы (5 и 8) — модель,
#      нашедшая первый переход, обычно принимает его за ответ и ставит 5 в обе
#      строки. Это главный разделитель между ступенями.
#
# Обе границы — на равенстве: в 4-м месяце варианты стоят одинаково, на 7-м
# накопленная разница ровно 0. Поэтому в обоих вопросах сказано «строго меньше»:
# модель, читающая условие невнимательно, ответит 4 и 7.

SYSTEM = (
    "Ты — аналитик планово-экономического отдела. Ты считаешь по шагам, "
    "показываешь промежуточные числа и заканчиваешь короткой рекомендацией "
    "для заказчика. Пишешь обычным текстом без markdown-разметки и строго "
    "соблюдаешь структуру ответа, заданную пользователем."
)

TASK = """Типография выбирает, как печатать этикетки.

Вариант А: аренда принтера 15 000 ₽/мес, расходники 1,20 ₽ за этикетку.
Вариант Б: покупка за 480 000 ₽ с равномерной амортизацией на 24 месяца,
обслуживание 6 000 ₽/мес, расходники 0,65 ₽ за этикетку.
В цехе 3 оператора с зарплатой 60 000 ₽ — они нужны при любом варианте.
Объём в первый месяц 14 000 этикеток, дальше растёт на 2 000 этикеток каждый месяц.

Определи:
1) точку равенства — при каком месячном объёме этикеток затраты по варианту А
   и по варианту Б за месяц равны;
2) первый месяц, начиная с которого затраты за сам этот месяц по варианту Б
   строго меньше, чем по варианту А;
3) первый месяц, начиная с которого суммарные затраты с первого месяца
   по этот включительно по варианту Б строго меньше, чем по варианту А.

Месяцы нумеруются с 1.

Отвечай обычным текстом, без markdown: без звёздочек, решёток, маркеров списка
и таблиц из вертикальных палочек. Структура ответа — ровно такая и в таком порядке:

РАСЧЁТ
1) Ежемесячные затраты варианта А при объёме q этикеток в месяц — формулой и с числами.
2) Ежемесячные затраты варианта Б при том же q — формулой и с числами.
3) Точка равенства: из какого уравнения она получена и чему равна.
4) Помесячная динамика, по одной строке на месяц, каждая строка в таком виде:
М<номер>: объём <шт>; А за месяц <руб>; Б за месяц <руб>; А накопительно <руб>; Б накопительно <руб>
Месяцев возьми столько, чтобы из этих строк были видны оба ответа — и на вопрос 2,
и на вопрос 3.

РЕКОМЕНДАЦИЯ
Три-четыре предложения простым языком, без формул: что выбрать и при каких
условиях вывод изменится.

Последними — ровно три строки, каждая с начала строки, и ничего после них:
ТОЧКА РАВЕНСТВА: <этикеток в месяц>
ЕЖЕМЕСЯЧНО ВЫГОДНЕЕ С: <номер месяца>
НАКОПИТЕЛЬНО ВЫГОДНЕЕ С: <номер месяца>

В этих трёх строках — только целые числа: без единиц измерения, без знака рубля,
без слова «месяц» и без пробелов внутри чисел."""

MESSAGES = [
    {"role": "system", "content": SYSTEM},
    {"role": "user", "content": TASK},
]

# Одинаково во всех трёх колонках: разницу должна давать только модель.
TEMPERATURE = 0.2

# Запас на самую многословную ступень. Развёрнутый ответ — это разбор из четырёх
# пунктов, восемь и больше строк помесячной динамики, абзац рекомендации и три
# итоговые строки; на кириллице это уже 2000–3000 токенов, а сильная ступень
# докладывает сверху reasoning, который тоже считается в лимит. Обрыв по
# max_tokens исказил бы сравнение сильнее, чем щедрый лимит: колонка с
# finish_reason=length теряет и итоговые строки, и часть разбора.
MAX_TOKENS = 6000

# Без него OpenRouter вправе увести запрос к другому провайдеру, и станет
# непонятно, чью задержку и чью цену мы измерили.
NO_FALLBACKS = {"provider": {"allow_fallbacks": False}}


def rung(label: str, model: str, note: str) -> Session:
    """Ступень лестницы. Отличается от соседней только полем model."""
    return Session(
        label=label,
        model=model,
        messages=MESSAGES,
        temperature=TEMPERATURE,
        max_tokens=MAX_TOKENS,
        note=note,
        extra_body=NO_FALLBACKS,
    )


