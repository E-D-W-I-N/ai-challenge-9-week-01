"""День 05 — одна задача, три ступени моделей: latency, токены и cost рядом.

Три колонки различаются ровно одним полем — `model`. Промпт, `temperature`,
`max_tokens` совпадают, иначе разницу в цифрах нельзя приписать модели.

Каждая колонка — ровно один вызов модели. Это сравнительный анализ
качества и цены, а не бенчмарк задержки.

Задача — оптимизация с ограничениями: набор заказов под лимиты веса и времени.
Посчитать в лоб её нельзя, надо перебирать варианты, и обе естественные жадные
стратегии дают неверный ответ. Модель отвечает разбором: рассмотренные наборы,
рекомендация диспетчеру и машиночитаемый хвост. Хвост — ось проверки
правильности, разбор — материал, по которому видна сила модели.
"""

