"""День 05 — одна задача, три ступени моделей: latency, токены, cost рядом.

Три колонки различаются ровно одним: id модели. Промпт, temperature, max_tokens
и число повторов одинаковы, иначе разницу нельзя приписать модели.

Задача с двумя ловушками и жёстким форматом — на ней слабая модель спотыкается
заметно, а не «отвечает то же самое, только дешевле».
"""

from __future__ import annotations

from app.schema import Scenario, Session

# ── Задача ──────────────────────────────────────────────────────────────────
#
# Ловушка №1 — средняя скорость. 30 км при 60 км/ч = 30 мин, 30 км при 40 км/ч
#   = 45 мин. 60 км за 75 мин → 48.0 км/ч, а не среднее арифметическое 50.
# Ловушка №2 — оплата. Платят за минуты в движении (75), а не за всю поездку
#   со стоянкой (90). 900 рублей, а не 1080.
# Отвлекающий факт — 8 коробок по 12 кг: на расчёт не влияет, но провоцирует
#   лишний шаг и ломает формат «ровно 5 строк».
#
# Правильный ответ целиком:
#   Шаг 1: 30
#   Шаг 2: 45
#   Шаг 3: 48.0
#   Шаг 4: 900
#   ОТВЕТ: 48.0; 900

SYSTEM = (
    "Ты — расчётный модуль курьерской службы. Ты выдаёшь только результат "
    "в заданном формате: без приветствий, без пояснений, без markdown, "
    "без пустых строк, без текста до и после."
)

TASK = """Курьер выезжает со склада в пункт выдачи и возвращается тем же маршрутом.
Расстояние в одну сторону — 30 км.
Туда он едет со средней скоростью 60 км/ч, обратно — со средней скоростью 40 км/ч.
В пункте выдачи он стоит 15 минут; стоянка не считается временем в движении.
В кузове 8 коробок по 12 кг.
Оплата водителю — 12 рублей за каждую минуту в движении; стоянка не оплачивается.

Посчитай:
1) время в движении туда, в минутах;
2) время в движении обратно, в минутах;
3) среднюю скорость на всём маршруте длиной 60 км без учёта стоянки, в км/ч;
4) оплату водителю, в рублях.

Формат ответа — ровно 5 строк, ни строкой больше:
Шаг 1: <число>
Шаг 2: <число>
Шаг 3: <число>
Шаг 4: <число>
ОТВЕТ: <число из шага 3>; <число из шага 4>

Единицы измерения не пиши, только числа. Число в шаге 3 и в строке ОТВЕТ —
с одним знаком после точки (например 12.5), остальные числа — целые."""

MESSAGES = [
    {"role": "system", "content": SYSTEM},
    {"role": "user", "content": TASK},
]

# Одинаково во всех трёх колонках: разницу должна давать только модель.
TEMPERATURE = 0.2
MAX_TOKENS = 1200
REPEATS = 4  # первый прогон — прогревочный, его отбрасываем; медиана по трём остальным

# Без него OpenRouter вправе увести запрос к другому провайдеру, и станет
# непонятно, чью задержку и чью цену мы измерили.
NO_FALLBACKS = {"provider": {"allow_fallbacks": False}}


def rung(label: str, model: str, note: str) -> Session:
    """Ступень лестницы. Отличается от соседней только полем model."""
    return Session(
        label=label,
        model=model,
        messages=MESSAGES,
        temperature=TEMPERATURE,
        max_tokens=MAX_TOKENS,
        repeats=REPEATS,
        note=note,
        extra_body=NO_FALLBACKS,
    )


