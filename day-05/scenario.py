# ── Задача и эталон ─────────────────────────────────────────────────────────
#
# Шесть заказов (вес кг, время мин, оплата ₽):
#   A 30 / 90 / 5000     B 25 / 60 / 4200     C 40 / 80 / 6000
#   D 20 / 50 / 3300     E 35 / 70 / 5200     F 15 / 40 / 2400
# Лимиты: не больше 100 кг и не больше 240 минут, заказ берётся целиком.
#
# Эталон (проверен полным перебором всех 64 подмножеств):
#   ОПТИМУМ: B + C + D + F = 15 900 ₽, вес ровно 100 кг, время 230 мин.
#   Решение единственное — второго набора с такой выручкой нет.
#   Допустимых непустых наборов 43.
#
